/**
 * build-mark-assets.ts — write the generated brand assets.
 *
 * Run with `npm run brand:assets`. Two kinds of output, both committed:
 *
 *  - `src/brand/*.svg` — the still and animated marks, and the social avatars.
 *  - the blocks between the `brand-mark:begin` / `brand-mark:end` markers in
 *    `src/style.css` and `src/index.md` — the loading screen's mark, as HTML
 *    elements and CSS transforms (see scripts/lib/brand-mark.ts for why it is
 *    not the SVG).
 *
 * Committed rather than built on deploy because the loader must paint from raw
 * HTML before any script runs; `tests/brand-mark.test.ts` fails if a committed
 * file no longer matches what the generator renders.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { markAssets, markLoaderCss, markLoaderHtml } from "../lib/brand-mark.js";

const SRC = join(process.cwd(), "src");

/** Replace the text between the markers, keeping the markers themselves. */
export function spliceGenerated(source: string, begin: string, end: string, body: string): string {
  const i = source.indexOf(begin);
  const j = source.indexOf(end);
  if (i === -1 || j === -1 || j < i) {
    throw new Error(`markers not found or out of order: ${begin} … ${end}`);
  }
  return source.slice(0, i + begin.length) + "\n" + body + "\n" + source.slice(j);
}

const CSS_BEGIN = "/* brand-mark:begin — generated, do not edit */";
const CSS_END = "/* brand-mark:end */";
const HTML_BEGIN = "<!-- brand-mark:begin — generated by `npm run brand:assets`, do not edit -->";
const HTML_END = "<!-- brand-mark:end -->";

for (const [path, svg] of Object.entries(markAssets())) {
  const target = join(SRC, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, svg, "utf8");
  process.stdout.write(`wrote src/${path} (${svg.length} bytes)\n`);
}

const cssPath = join(SRC, "style.css");
const css = spliceGenerated(readFileSync(cssPath, "utf8"), CSS_BEGIN, CSS_END, markLoaderCss());
writeFileSync(cssPath, css, "utf8");
process.stdout.write(`spliced the mark into src/style.css (${markLoaderCss().length} bytes of CSS)\n`);

const htmlPath = join(SRC, "index.md");
const html = spliceGenerated(readFileSync(htmlPath, "utf8"), HTML_BEGIN, HTML_END, "  " + markLoaderHtml());
writeFileSync(htmlPath, html, "utf8");
process.stdout.write(`spliced the mark into src/index.md (${markLoaderHtml().length} bytes of markup)\n`);
